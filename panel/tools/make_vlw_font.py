"""Make the smooth fonts of the panel as C arrays in TFT_eSPI's VLW format (Liam 05/11,
PANEL session: "làm theo bản mới đi", new screens with smooth fonts).

The VLW layout is the one TFT_eSPI 2.5.43 reads (Extensions/Smooth_font.cpp, loadFont /
loadMetrics / drawGlyph), all integers 32-bit big-endian:
  header  gCount, version (11), size, 0, ascent (top of 'd'), descent (bottom of 'p')
  glyphs  gCount x { unicode, height, width, xAdvance, dY (baseline to top, up = +),
                     dX (cursor to left edge), 0 }
  bitmaps 8-bit alpha, width x height each, in glyph order
TFT_eSPI puts the top of a glyph at cursor_y + ascent - dY and moves the cursor by xAdvance;
a space is (ascent + descent) / 4 wide. A code point missing from the font is drawn as an
empty box, so every string the panel draws must use only the characters listed here.

Source fonts: DejaVu Sans and DejaVu Sans Bold as shipped with matplotlib (free licence,
Bitstream Vera + DejaVu changes; embedding allowed, notice in src/fonts/LICENSE_DEJAVU).
Rasterised with Pillow at the pixel size given (TrueType em size), no hinting choice made.

Run from panel/:   python tools/make_vlw_font.py
Writes src/fonts/*.h and src/fonts/LICENSE_DEJAVU. Generated files: do not edit by hand.
"""
from __future__ import annotations

import pathlib
import shutil

import matplotlib
from PIL import Image, ImageDraw, ImageFont

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / 'src' / 'fonts'
TTF = pathlib.Path(matplotlib.__file__).parent / 'mpl-data' / 'fonts' / 'ttf'

ASCII = ''.join(chr(c) for c in range(0x21, 0x7F))      # space is not a glyph in VLW
EXTRA = 'µ·'                                   # µ ·
FONTS = [  # name, ttf, pixel size, characters
    ('ui_font_small', 'DejaVuSans.ttf', 13, ASCII + EXTRA),
    ('ui_font_body', 'DejaVuSans.ttf', 17, ASCII + EXTRA),
    ('ui_font_bold', 'DejaVuSans-Bold.ttf', 17, ASCII + EXTRA),
    ('ui_font_head', 'DejaVuSans-Bold.ttf', 24, ASCII + EXTRA),
    ('ui_font_big', 'DejaVuSans-Bold.ttf', 56, '0123456789.-?Es'),
]


def be32(v: int) -> bytes:
    return (v & 0xFFFFFFFF).to_bytes(4, 'big')


def vlw(ttf: pathlib.Path, size: int, chars: str) -> bytes:
    f = ImageFont.truetype(str(ttf), size)
    ascent = -f.getbbox('d', anchor='ls')[1]
    descent = f.getbbox('p', anchor='ls')[3]
    metrics, bitmaps = [], []
    for ch in sorted(set(chars)):
        x0, y0, x1, y1 = f.getbbox(ch, anchor='ls')
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        adv = int(round(f.getlength(ch)))
        assert w < 256 and h < 256 and adv < 256 and -128 <= x0 < 128, (ch, w, h, adv, x0)
        img = Image.new('L', (max(w, 1), max(h, 1)), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=f, fill=255, anchor='ls')
        raw = img.tobytes() if w and h else b''
        metrics.append(be32(ord(ch)) + be32(h) + be32(w) + be32(adv) + be32(-y0) + be32(x0) + be32(0))
        bitmaps.append(raw)
    head = be32(len(metrics)) + be32(11) + be32(size) + be32(0) + be32(ascent) + be32(descent)
    return head + b''.join(metrics) + b''.join(bitmaps)


def c_array(name: str, data: bytes, src: str) -> str:
    rows = [', '.join('0x%02X' % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return ('/* %s.h - generated by panel/tools/make_vlw_font.py from %s; do not edit.\n'
            ' * TFT_eSPI smooth font (VLW), %d bytes. Licence: LICENSE_DEJAVU. */\n'
            '#pragma once\n#include <stdint.h>\n\n'
            'static const uint8_t %s[] = {\n    %s\n};\n') % (name, src, len(data), name,
                                                            ',\n    '.join(rows))


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, ttf, size, chars in FONTS:
        data = vlw(TTF / ttf, size, chars)
        (OUT / (name + '.h')).write_text(c_array(name, data, '%s %d px' % (ttf, size)), encoding='ascii')
        print('%-14s %-20s %3d px %3d glyphs %7d bytes' % (name, ttf, size, len(set(chars)), len(data)))
    shutil.copyfile(TTF / 'LICENSE_DEJAVU', OUT / 'LICENSE_DEJAVU')


if __name__ == '__main__':
    main()
