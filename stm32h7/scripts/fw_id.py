#!/usr/bin/env python3
"""
fw_id.py: CubeIDE pre-build step of the H7 project (Debug and Release, .cproject `prebuildStep`), the H7
side of the firmware id (#fw, Liam 09/11, CODE: STATUS_CODE L61 b; AGV twin: AGV scripts/build_id.py).

Writes stm32h7/Core/Inc/fw_id_gen.h with the git commit of this checkout, whether the tree is dirty and the
build configuration:
    #define FW_GIT_SHA   "<12 hex>"   ("unknown" when git fails)
    #define FW_GIT_DIRTY 0|1
    #define FW_ENV       "Debug"
main.c prints `#fw sha=.. dirty=.. env=..` at boot and every 10 s in the debug block, so meta.yaml takes the
H7 commit from the board, not from HEAD on the PC (03_CODE/CLAUDE.md, "Nhận dạng firmware").

The header is in .gitignore, so writing it does not make the tree dirty; it is rewritten only when its text
changes, so an unchanged commit does not rebuild main.c. Files git does not report (ignored: Debug/, the
header; skip-worktree: .settings/language.settings.xml) never count as dirty.

  python stm32h7/scripts/fw_id.py [Debug]          (CubeIDE passes ${ConfigName})
Prints one line `fw_id: <sha> dirty=<0|1> env=<cfg>` (in the CubeIDE build console). Exit 0 always, so a
missing git does not stop the build; the board then prints sha=unknown dirty=1, which every check refuses.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.dirname(HERE)                         # stm32h7/
OUT = os.path.join(PROJ, 'Core', 'Inc', 'fw_id_gen.h')
NOT_SOURCE = ('stm32h7/.settings/language.settings.xml',)


def git(*args):
    try:
        return subprocess.run(['git', '-C', PROJ] + list(args), capture_output=True, text=True,
                              check=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None


def fw_id(cfg):
    sha = (git('rev-parse', '--short=12', 'HEAD') or 'unknown').strip() or 'unknown'
    status = git('status', '--porcelain')            # whole repo: the H7 build also reads shared headers
    # CubeIDE rewrites only the env-hash of .settings/language.settings.xml on a build (03_CODE/CLAUDE.md,
    # skip-worktree in the main folder): not a source change, so not dirty in any clone
    changed = [] if status is None else [l for l in status.splitlines()
                                         if l[3:].strip() and not l[3:].strip().endswith(NOT_SOURCE)]
    dirty = 1 if (status is None or sha == 'unknown' or changed) else 0
    return sha, dirty, cfg


def header_text(sha, dirty, cfg):
    return ('// Generated by stm32h7/scripts/fw_id.py at build time (CubeIDE pre-build); do not edit, not in git.\n'
            '#pragma once\n'
            f'#define FW_GIT_SHA   "{sha}"\n'
            f'#define FW_GIT_DIRTY {dirty}\n'
            f'#define FW_ENV       "{cfg}"\n')


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    cfg = (argv[0] if argv else 'Debug').strip() or 'Debug'
    sha, dirty, cfg = fw_id(cfg)
    text = header_text(sha, dirty, cfg)
    old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if old != text:
        with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
    print(f'fw_id: {sha} dirty={dirty} env={cfg}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
